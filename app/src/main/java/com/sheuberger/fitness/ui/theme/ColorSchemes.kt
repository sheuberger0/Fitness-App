/**
 * Alle Farben eines dunklen Farbschemas, aus denen [FitnessTheme] das Material-Farbschema baut.
 *
 * Entworfen wurden die Schemata im Farbraum OKLCH (Helligkeit, Buntheit, Farbton). Dort sehen gleiche
 * Helligkeitswerte auch gleich hell aus, egal welcher Farbton. Deshalb haben alle Schemata dieselbe Abstufung der
 * Flächen (dim → background → card → container …), nur der Farbton wechselt. Dass jede Schrift lesbar bleibt
 * (mindestens 4,5:1 Kontrast nach WCAG), prüft ColorSchemesTest für jedes Schema.
 */
@Immutable
data class DarkPalette(
    /** Seitenhintergrund. */
    val background: Color,
    /** Noch etwas dunkler als der Hintergrund. */
    val dim: Color,
    /** Karten, Sheets und Dialoge. */
    val card: Color,
    /** Flächen in Karten (Felder, Chips, Tonal-Buttons), von dezent bis kräftig. */
    val container: Color,
    val containerHigh: Color,
    val containerHighest: Color,
    val outline: Color,
    val onSurface: Color,
    /** Zweitrangiger Text. */
    val onSurfaceVariant: Color,
    /** Gegenfarbe, z. B. für die Snackbar. */
    val inverseSurface: Color,
    val inverseOnSurface: Color,
    /** Akzent für Text, Linien und Symbole: hell genug für 4,5:1 auf Hintergrund und Karte. */
    val accent: Color,
    /** Schrift auf dem Akzent (z. B. der gewählte Tag im Kalender). */
    val onAccent: Color,
    /**
     * Gefüllte Buttons, FAB und "+". Darf dunkler sein als [accent] (z. B. tiefes Burgund),
     * die Schrift darauf ([onAccentFill]) ist dann hell.
     */
    val accentFill: Color,
    val onAccentFill: Color,
    /** Zarte Akzentfläche: ausgewählter Tab, Chips, "Platz 1". */
    val accentContainer: Color,
    val onAccentContainer: Color,
    /** Akzent auf der Gegenfarbe (z. B. "Rückgängig" in der Snackbar). */
    val inverseAccent: Color,
    /**
     * Fortschritt und Rückschritt. Bei roten Schemata ist der Rückschritt bernsteinfarben,
     * damit "schlechter" nicht wie "ausgewählt" aussieht.
     */
    val positive: Color,
    val negative: Color,
    /** Löschen und Fehler: bleibt immer rot. */
    val error: Color,
)

